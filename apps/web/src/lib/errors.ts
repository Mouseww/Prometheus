/** 用当前界面语言渲染后端错误；不是错误码时原样返回。 */
export function localizeError(raw: string): string {
	const decoded = decodeError(raw);
	if (!decoded) return raw;
	const lang = usePrefs.getState().lang;
	const vars: Record<string, string> = {};
	for (const [k, v] of Object.entries(decoded.params)) {
		// 有些参数本身就是一串错误码（网关字段校验），逐条翻译后再拼回去。
		vars[k] = v.includes(ERROR_PREFIX) ? v.split("\n").map((line) => localizeError(line)).join("\n") : v;
	}
	return translate(M, lang, decoded.code as Msg, vars);
}

