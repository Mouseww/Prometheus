// Turns modes/*.md into src/bundled/*.ts so the text is compiled into the app.
// A plain readFile on a .md works in dev and fails in every packaged build (esbuild only follows imports).
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const src = join(root, "assets");
const out = join(root, "src", "bundled");
mkdirSync(out, { recursive: true });

const files = readdirSync(src).filter((f) => f.endsWith(".md")).sort();
for (const file of files) {
	const text = readFileSync(join(src, file), "utf8");
	const name = file.replace(/\.md$/, "").replace(/\./g, "_");
	writeFileSync(
		join(out, `${name}.ts`),
		`// Generated by scripts/embed-modes.mjs from assets/${file} — do not edit by hand.\nexport const TEXT = ${JSON.stringify(text)};\n`,
	);
	console.log(`embedded modes/${file} -> src/bundled/${name}.ts (${text.length} chars)`);
}
