// Turns drivers/<platform>/* into src/driver/embedded.generated.ts so the driver sources are compiled
// into the app. A plain readFile next to the source works in dev and fails in every packaged build
// (esbuild only follows imports). Run after editing anything under drivers/: `pnpm embed`.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const drivers = join(root, "drivers");
const out = join(root, "src", "driver", "embedded.generated.ts");

const platforms = {};
for (const platform of readdirSync(drivers).sort()) {
	const files = {};
	for (const file of readdirSync(join(drivers, platform)).sort()) {
		files[file] = readFileSync(join(drivers, platform, file), "utf8").replace(/\r\n/g, "\n");
	}
	const hash = createHash("sha256").update(JSON.stringify(files)).digest("hex").slice(0, 16);
	platforms[platform] = { hash, files };
	console.log(`embedded drivers/${platform} (${Object.keys(files).join(", ")}) hash=${hash}`);
}
writeFileSync(
	out,
	`// Generated by scripts/embed-drivers.mjs from drivers/ — do not edit by hand.\n` +
		`export const DRIVERS: Record<string, { hash: string; files: Record<string, string> }> = ${JSON.stringify(platforms, null, "\t")};\n`,
);
